/**
 * Schedule activities for the demo projects.
 *
 * Invented, like everything else in the demo. The point of this file is that
 * the Schedule tab has to look like a real construction programme the moment
 * it opens - a builder can tell a plausible sequence from a made-up one in
 * about three seconds, and an empty or nonsense Gantt kills the pitch.
 *
 * So the sequences below are the actual order these jobs happen in: you cannot
 * plaster before blockwork, conduiting runs alongside blockwork rather than
 * after it, and the slab has to cure before columns go up on top of it.
 *
 * Baselines are generated by running the CPM engine twice - once on the clean
 * plan, which is saved as the baseline, and again with the real-world delays
 * applied. That means the variance figures on screen are genuinely calculated
 * rather than typed in, and they stay consistent if anyone edits a duration
 * mid-demo.
 */

