export interface ScheduleSeedProject {
  id: string;
  start: number;
  /**
   * The project's agreed completion date. Activity durations are scaled so the
   * baseline lands here, which keeps the schedule consistent with the dates
   * already shown on the dashboard and the project list. Without it a template
   * that happens to be shorter than the project's real span finishes in the
   * past, and every activity reads as complete.
   */
  due: number;
  template: 'build' | 'renovation';
  singleStorey?: boolean;
  /**
   * Real-world slippage: this activity actually started N working days after
   * the plan said it would. Everything downstream moves, which is exactly the
   * moment the Schedule tab earns its keep.
   */
  delay?: { key: string; workingDaysLate: number; reason: string };
}

const DAY = 24 * 60 * 60 * 1000;

/**
 * Builds and stores the activities for one project.
 *
 * Runs the schedule twice on purpose: pass one produces the clean plan that is
 * frozen as the baseline, pass two applies the delay so the live dates differ
 * from it. Doing it this way means the "12 days late" on screen was computed,
 * not authored.
 */
export function seedProjectSchedule(p: ScheduleSeedProject): number {
  const rows = (p.template === 'build' ? BUILD_TEMPLATE : RENOVATION_TEMPLATE).filter(
    (r) => !(p.singleStorey && r.upperFloor),
  );

  const idFor = (key: string) => `${p.id}_act_${key}`;
  const present = new Set(rows.map((r) => r.key));

  const raw: ScheduleActivity[] = rows.map((r, i) => ({
    id: idFor(r.key),
    projectId: p.id,
    stageId: `${p.id}_stage_${r.stage}`,
    name: r.name,
    order: i + 1,
    durationDays: r.days,
    percentComplete: 0,
    budgetedCost: r.budget,
    predecessors: (r.after ?? [])
      // A dropped upper-floor row must not leave a dangling link behind it.
      .filter((a) => present.has(typeof a === 'string' ? a : a.key))
      .map((a) =>
        typeof a === 'string'
          ? { predecessorId: idFor(a), type: 'FS' as DependencyType, lagDays: 0 }
          : { predecessorId: idFor(a.key), type: a.type, lagDays: a.lag ?? 0 },
      ),
  }));

  // Stretch or squeeze the template so the plan runs from the project's start
  // to its agreed completion date. The shape of the programme - the sequence,
  // the overlaps, which chain is critical - is unaffected; only the scale is.
  const natural = computeSchedule(raw, { projectStart: p.start }).durationWorkingDays;
  const target = workingDaysBetween(p.start, p.due);
  const factor = natural > 0 && target > 0 ? target / natural : 1;

  const base: ScheduleActivity[] = raw.map((a) => ({
    ...a,
    // Milestones stay at zero; everything else keeps at least a day.
    durationDays: a.durationDays === 0 ? 0 : Math.max(1, Math.round(a.durationDays * factor)),
  }));

  const delayedActivityId = p.delay ? idFor(p.delay.key) : undefined;

  // Pass one: the clean plan. These dates become the baseline.
  const planned = computeSchedule(base, { projectStart: p.start });

  // Pass two: apply the slippage and re-run, giving the dates the job is
  // actually running to.
  const delayed: ScheduleActivity[] = base.map((a) =>
    a.id === delayedActivityId && p.delay
      ? {
          ...a,
          actualStart: planned.byId[a.id].startDate + p.delay.workingDaysLate * DAY,
          delayReason: p.delay.reason,
        }
      : a,
  );
  const current = computeSchedule(delayed, { projectStart: p.start });

  // Pass three: progress is read off the LIVE dates against today, not off the
  // baseline. Using the baseline would mark work complete that the delay has
  // not let anyone start yet - which is exactly the sort of contradiction a
  // builder spots on screen in about two seconds.
  const now = Date.now();

  const live: ScheduleActivity[] = base.map((a) => {
    const plan = planned.byId[a.id];
    const actual = current.byId[a.id];

    const percentComplete = progressAt(now, actual.startDate, actual.finishDate);

    const activity: ScheduleActivity = {
      ...a,
      percentComplete,
      baselineStart: plan.startDate,
      baselineFinish: plan.finishDate,
    };

    // Work that has started carries the date it really began; work that has
    // finished carries both.
    if (percentComplete > 0) activity.actualStart = actual.startDate;
    if (percentComplete >= 100) activity.actualFinish = actual.finishDate;

    if (a.id === delayedActivityId && p.delay) {
      activity.actualStart = actual.startDate;
      activity.actualFinish = undefined;
      activity.delayReason = p.delay.reason;
    }

    return activity;
  });

  live.forEach((a) => {
    store.set(`projects/${p.id}/schedule`, a.id, {
      ...a,
      createdAt: Date.now(),
      updatedAt: Date.now(),
      createdBy: OWNER_UID,
      updatedBy: OWNER_UID,
    });
  });

  // Hand back the duration-weighted completion so the project record can carry
  // the same number. Otherwise the Overview tab quotes one percentage and the
  // Schedule tab beside it quotes another, which is the first thing anyone
  // notices when two tabs are open in front of them.
  const weight = live.reduce((t, a) => t + Math.max(1, a.durationDays), 0);
  const done = live.reduce((t, a) => t + Math.max(1, a.durationDays) * (a.percentComplete / 100), 0);
  return weight > 0 ? Math.round((done / weight) * 100) : 0;
}

/**
 * How far through an activity today is - finished if it is behind us, not
 * started if it is ahead, and proportionally along if we are inside it.
 * Rounded to 5% so the demo reads like someone's estimate rather than a
 * computer's arithmetic.
 */
function progressAt(now: number, start: number, finish: number): number {
  if (now >= finish + DAY) return 100;
  if (now < start) return 0;
  const span = finish + DAY - start;
  if (span <= 0) return 100;
  return Math.min(95, Math.max(5, Math.round(((now - start) / span) * 20) * 5));
}
